@file:OptIn(kotlin.js.ExperimentalWasmJsInterop::class, kotlin.wasm.unsafe.UnsafeWasmMemoryApi::class)

package sk.ainet.exec.wasm

import kotlinx.coroutines.await
import kotlin.js.Promise
import kotlin.wasm.unsafe.Pointer
import kotlin.wasm.unsafe.wasmMemory
import kotlin.wasm.unsafe.withScopedMemoryAllocator

/**
 * The bridge to the SIMD128 kernel sidecar (SKEEP-007 §T1).
 *
 * Kotlin/Wasm has no SIMD types and no shared-memory threads, so the kernels live in a second wasm
 * module compiled from the engine's C sources by Emscripten (`native/build-wasm.sh`). That module
 * owns its own linear memory. Weights are uploaded into it **once** per weight ([weightHandle]) and
 * stay there; activations cross per call. Both directions go through Kotlin's own linear memory —
 * a Kotlin array is a GC object JavaScript cannot see, so it is staged with
 * [withScopedMemoryAllocator] (a wasm loop, no interop per element) and copied across with one
 * `Uint8Array.set` per chunk.
 *
 * Nothing here is reached until [initialize] has completed; every consumer checks [isReady] and
 * falls back to the scalar path otherwise, so a page that never awaits the sidecar still works.
 */
public object WasmKernels {
    private var module: JsAny? = null
    private var modeName: String = "none"

    /** `true` once the sidecar is instantiated. */
    public val isReady: Boolean get() = module != null

    /** `"simd128-st"`, `"simd128-mt"` or `"none"`; the kernel names carry it so traces show the tier. */
    public val mode: String get() = modeName

    /**
     * Instantiate the sidecar. [threads] `null` picks the pthreads build when the page is
     * cross-origin isolated (or when running under Node). The module is embedded in this library
     * ([SidecarArtifacts], generated by `native/build-wasm.sh`) and instantiated from a `data:` URL
     * with the wasm bytes handed to Emscripten directly — no file to host, no path to configure.
     * [url] instead loads an externally hosted `skainet_kernels_*.mjs` (with its `.wasm` beside it).
     * Idempotent.
     */
    public suspend fun initialize(url: String? = null, threads: Boolean? = null) {
        if (module != null) return
        val mt = threads ?: canUseThreads()
        module = if (url != null) {
            loadSidecar(url).await<JsAny>()
        } else {
            val mjs = if (mt) SidecarArtifacts.MT_MJS else SidecarArtifacts.ST_MJS
            val wasm = if (mt) SidecarArtifacts.MT_WASM else SidecarArtifacts.ST_WASM
            loadEmbeddedSidecar(mjs, wasm).await<JsAny>()
        }
        modeName = if (mt) "simd128-mt" else "simd128-st"
    }

    /** Drop the sidecar and every cached weight; the next [initialize] starts over. Tests only. */
    public fun clearForTesting() {
        module = null
        modeName = "none"
        weightHandles.clear()
    }

    private fun mod(): JsAny = checkNotNull(module) { "WasmKernels.initialize() has not completed" }

    // ── memory ────────────────────────────────────────────────────────────────────────────────────

    /** Byte address in sidecar memory. */
    public fun alloc(bytes: Int): Int = jsMalloc(mod(), bytes)
    public fun free(ptr: Int): Unit = jsFree(mod(), ptr)

    private const val CHUNK_BYTES = 4 * 1024 * 1024

    /** Copy [count] floats from [src] into sidecar memory at [dstPtr]. */
    public fun writeFloats(dstPtr: Int, src: FloatArray, srcOffset: Int, count: Int) {
        val m = mod()
        var done = 0
        while (done < count) {
            val n = minOf(count - done, CHUNK_BYTES / 4)
            withScopedMemoryAllocator { allocator ->
                val base = allocator.allocate(n * 4)
                var p: Pointer = base
                for (i in 0 until n) {
                    p.storeInt(src[srcOffset + done + i].toRawBits())
                    p = p + 4
                }
                jsCopyIn(m, wasmMemory, base.address.toInt(), dstPtr + done * 4, n * 4)
            }
            done += n
        }
    }

    /** Copy [count] floats from sidecar memory at [srcPtr] into [dst]. */
    public fun readFloats(srcPtr: Int, dst: FloatArray, dstOffset: Int, count: Int) {
        val m = mod()
        var done = 0
        while (done < count) {
            val n = minOf(count - done, CHUNK_BYTES / 4)
            withScopedMemoryAllocator { allocator ->
                val base = allocator.allocate(n * 4)
                jsCopyOut(m, wasmMemory, srcPtr + done * 4, base.address.toInt(), n * 4)
                var p: Pointer = base
                for (i in 0 until n) {
                    dst[dstOffset + done + i] = Float.fromBits(p.loadInt())
                    p = p + 4
                }
            }
            done += n
        }
    }

    /** Copy [count] bytes from [src] into sidecar memory at [dstPtr]. */
    public fun writeBytes(dstPtr: Int, src: ByteArray, srcOffset: Int, count: Int) {
        val m = mod()
        var done = 0
        while (done < count) {
            val n = minOf(count - done, CHUNK_BYTES)
            withScopedMemoryAllocator { allocator ->
                val base = allocator.allocate(n)
                var p: Pointer = base
                var i = 0
                // Four bytes per store where possible; the tail byte by byte.
                while (i + 4 <= n) {
                    val o = srcOffset + done + i
                    val v = (src[o].toInt() and 0xFF) or ((src[o + 1].toInt() and 0xFF) shl 8) or
                        ((src[o + 2].toInt() and 0xFF) shl 16) or ((src[o + 3].toInt() and 0xFF) shl 24)
                    p.storeInt(v)
                    p = p + 4
                    i += 4
                }
                while (i < n) {
                    p.storeByte(src[srcOffset + done + i])
                    p = p + 1
                    i++
                }
                jsCopyIn(m, wasmMemory, base.address.toInt(), dstPtr + done, n)
            }
            done += n
        }
    }

    // ── resident weights ──────────────────────────────────────────────────────────────────────────

    private class Resident(val ptr: Int, val bytes: Int)
    private val weightHandles = HashMap<Any, Resident>()

    /**
     * The sidecar address of [bytes]`[offset, offset + length)`, uploaded on first use and reused
     * afterwards — the "once per weight, not once per call" rule of every pack in the tree. Keyed on
     * the array's identity: a model's parameters are immutable once loaded.
     */
    public fun weightHandle(bytes: ByteArray, offset: Int, length: Int): Int {
        val key: Any = if (offset == 0 && length == bytes.size) bytes else Triple(bytes, offset, length)
        weightHandles[key]?.let { return it.ptr }
        val ptr = alloc(length)
        writeBytes(ptr, bytes, offset, length)
        weightHandles[key] = Resident(ptr, length)
        return ptr
    }

    /**
     * The sidecar address of a dense FP32 weight ([floats]), uploaded once and reused — the dense
     * counterpart of [weightHandle]. Without it a single-token `x · Wᵀ` re-uploads the whole weight
     * per call and runs at the copy's speed, not the kernel's.
     */
    public fun denseWeightHandle(floats: FloatArray): Int {
        weightHandles[floats]?.let { return it.ptr }
        val ptr = alloc(floats.size * 4)
        writeFloats(ptr, floats, 0, floats.size)
        weightHandles[floats] = Resident(ptr, floats.size * 4)
        return ptr
    }

    /** Free the sidecar copy of a dense weight; call when a model is unloaded. */
    public fun release(floats: FloatArray) {
        weightHandles.remove(floats)?.let { free(it.ptr) }
    }

    /** Free the sidecar copy of [bytes]; call when a model is unloaded. */
    public fun release(bytes: ByteArray) {
        val it = weightHandles.entries.iterator()
        while (it.hasNext()) {
            val e = it.next()
            val k = e.key
            val same = k === bytes || (k is Triple<*, *, *> && k.first === bytes)
            if (same) {
                free(e.value.ptr)
                it.remove()
            }
        }
    }

    /** Bytes currently resident in the sidecar as weights. */
    public fun residentWeightBytes(): Long = weightHandles.values.sumOf { it.bytes.toLong() }

    // ── kernels ───────────────────────────────────────────────────────────────────────────────────

    /** `skainet_<fmt>_matmul_rm` / `skainet_<fmt>_matmul`: one activation row against a packed weight. */
    public fun packedMatmul(fnName: String, inPtr: Int, weightPtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
        jsPackedMatmul(mod(), fnName, inPtr, weightPtr, inputDim, outputDim, outPtr)

    /** `skainet_fp32_matmul`: `C(m,n) = A(m,k) · B(k,n)`, strides in floats. */
    public fun fp32Matmul(aPtr: Int, aStride: Int, bPtr: Int, bStride: Int, cPtr: Int, cStride: Int, m: Int, n: Int, k: Int): Unit =
        jsFp32Matmul(mod(), aPtr, aStride, bPtr, bStride, cPtr, cStride, m, n, k)

    /** `skainet_fp32_matmul_wt`: `out(m,n) = in(m,k) · w(n,k)ᵀ`. */
    public fun fp32MatmulWt(inPtr: Int, wPtr: Int, outPtr: Int, m: Int, n: Int, k: Int): Unit =
        jsFp32MatmulWt(mod(), inPtr, wPtr, outPtr, m, n, k)

    /**
     * `skainet_bf16_matmul` / `skainet_fp16_matmul`: `C(m,n) = A(m,k) · B(k,n)` with `B` stored as
     * 16-bit floats, strides in floats for `A`/`C` and in bytes for `B`.
     */
    public fun narrowFloatMatmul(fnName: String, aPtr: Int, aStride: Int, bPtr: Int, bByteStride: Int, cPtr: Int, cStride: Int, m: Int, n: Int, k: Int): Unit =
        jsNarrowFloatMatmul(mod(), fnName, aPtr, aStride, bPtr, bByteStride, cPtr, cStride, m, n, k)

    /**
     * `skainet_ternary_f32_gemv`: one FP32 activation row against a sequentially packed BitNet b1.58
     * weight (`inputDim / 4` bytes per output row), per-tensor scale not applied.
     */
    public fun ternaryF32Gemv(inPtr: Int, weightPtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
        jsTernaryF32Gemv(mod(), inPtr, weightPtr, inputDim, outputDim, outPtr)

    /**
     * `skainet_ternary_lmhead_stage1`: four planes at [planesPtr] (each [planeStrideBytes] apart) with
     * the fused weights `{1, ⅓, ⅑, 1/27}`, times the FP16 row scales at [rowScalePtr].
     */
    public fun ternaryLmheadStage1(inPtr: Int, planesPtr: Int, planeStrideBytes: Int, rowScalePtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
        jsTernaryLmheadStage1(mod(), inPtr, planesPtr, planeStrideBytes, rowScalePtr, inputDim, outputDim, outPtr)

    /** `skainet_bitnet_gemv_tq2_0`: int8 activation codes with one absmax scale against TQ2_0 blocks. */
    public fun bitnetGemvTq2_0(activationPtr: Int, activationScale: Float, weightPtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
        jsBitnetGemvTq2_0(mod(), activationPtr, activationScale, weightPtr, inputDim, outputDim, outPtr)

    // ── diagnostics ───────────────────────────────────────────────────────────────────────────────

    /**
     * What the sidecar runs on — the wasm counterpart of the JVM's provider banner and CPU-feature
     * probes. [hardwareConcurrency] is the browser's (or Node's) logical core count, [threads] whether
     * the pthreads build is loaded (it only is when [crossOriginIsolated] or under Node).
     */
    public data class SidecarFeatures(
        val mode: String,
        val simd128: Boolean,
        val threads: Boolean,
        val crossOriginIsolated: Boolean,
        val hardwareConcurrency: Int,
        val residentWeightBytes: Long,
    ) {
        override fun toString(): String =
            "mode=$mode simd128=$simd128 threads=$threads crossOriginIsolated=$crossOriginIsolated " +
                "cores=$hardwareConcurrency residentWeightBytes=$residentWeightBytes"
    }

    /** Current sidecar capabilities; `mode == "none"` before [initialize]. */
    public fun features(): SidecarFeatures = SidecarFeatures(
        mode = modeName,
        simd128 = isReady,
        threads = modeName == "simd128-mt",
        crossOriginIsolated = jsCrossOriginIsolated(),
        hardwareConcurrency = jsHardwareConcurrency(),
        residentWeightBytes = if (isReady) residentWeightBytes() else 0L,
    )
}

// ── JS glue ───────────────────────────────────────────────────────────────────────────────────────

private fun canUseThreads(): Boolean = js(
    "(typeof crossOriginIsolated !== 'undefined' && crossOriginIsolated === true) || (typeof process !== 'undefined' && process.versions != null && process.versions.node != null)",
)

// The import goes through `Function` so a bundler (webpack, in every Kotlin/Wasm browser build) does
// not try to resolve the sidecar at build time: it is a runtime URL next to the application bundle,
// not a module of the application. Node and browsers both honour a dynamic import of an absolute URL.
private fun loadSidecar(url: String): Promise<JsAny> = js("(new Function('u', 'return import(u)'))(url).then(m => m.default())")

// Embedded form. The wasm bytes go in as `wasmBinary`, so Emscripten performs no fetch. The glue is
// imported from a data: URL under Node (which also accepts data: URLs for worker_threads) and from a
// same-origin blob: URL in a browser (a Blob worker keeps the page's origin, which a pthreads build
// needs to share its memory with the page; a data: worker would be opaque-origin).
// `mainScriptUrlOrBlob` tells the pthreads build where its workers find the same glue.
private fun loadEmbeddedSidecar(mjsBase64: String, wasmBase64: String): Promise<JsAny> = js(
    """
    (function() {
      var bin = Uint8Array.from(atob(wasmBase64), function (c) { return c.charCodeAt(0); });
      var isNode = typeof process !== 'undefined' && process.versions != null && process.versions.node != null;
      var url, main;
      if (isNode) {
        url = 'data:text/javascript;base64,' + mjsBase64;
        main = url;
      } else {
        main = new Blob([atob(mjsBase64)], { type: 'text/javascript' });
        url = URL.createObjectURL(main);
      }
      return (new Function('u', 'return import(u)'))(url)
        .then(function (m) { return m.default({ wasmBinary: bin, mainScriptUrlOrBlob: main }); });
    })()
    """,
)

private fun jsMalloc(mod: JsAny, bytes: Int): Int = js("mod._malloc(bytes)")

private fun jsFree(mod: JsAny, ptr: Int): Unit = js("mod._free(ptr)")

private fun jsCopyIn(mod: JsAny, kmem: JsAny, srcPtr: Int, dstPtr: Int, bytes: Int): Unit =
    js("new Uint8Array(mod.wasmMemory.buffer).set(new Uint8Array(kmem.buffer, srcPtr, bytes), dstPtr)")

private fun jsCopyOut(mod: JsAny, kmem: JsAny, srcPtr: Int, dstPtr: Int, bytes: Int): Unit =
    js("new Uint8Array(kmem.buffer).set(new Uint8Array(mod.wasmMemory.buffer, srcPtr, bytes), dstPtr)")

private fun jsPackedMatmul(mod: JsAny, fnName: String, inPtr: Int, weightPtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
    js("mod[fnName](inPtr, 0, weightPtr, 0, inputDim, outputDim, outPtr, 0)")

private fun jsFp32Matmul(mod: JsAny, aPtr: Int, aStride: Int, bPtr: Int, bStride: Int, cPtr: Int, cStride: Int, m: Int, n: Int, k: Int): Unit =
    js("mod._skainet_fp32_matmul(aPtr, 0, aStride, bPtr, 0, bStride, cPtr, 0, cStride, m, n, k)")

private fun jsFp32MatmulWt(mod: JsAny, inPtr: Int, wPtr: Int, outPtr: Int, m: Int, n: Int, k: Int): Unit =
    js("mod._skainet_fp32_matmul_wt(inPtr, 0, wPtr, 0, outPtr, 0, m, n, k)")

private fun jsNarrowFloatMatmul(mod: JsAny, fnName: String, aPtr: Int, aStride: Int, bPtr: Int, bByteStride: Int, cPtr: Int, cStride: Int, m: Int, n: Int, k: Int): Unit =
    js("mod[fnName](aPtr, 0, aStride, bPtr, 0, bByteStride, cPtr, 0, cStride, m, n, k)")

private fun jsTernaryF32Gemv(mod: JsAny, inPtr: Int, weightPtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
    js("mod._skainet_ternary_f32_gemv(inPtr, 0, weightPtr, 0, inputDim, outputDim, outPtr, 0)")

private fun jsTernaryLmheadStage1(mod: JsAny, inPtr: Int, planesPtr: Int, planeStrideBytes: Int, rowScalePtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
    js("mod._skainet_ternary_lmhead_stage1(inPtr, 0, planesPtr, 0, planeStrideBytes, rowScalePtr, 0, inputDim, outputDim, outPtr, 0)")

private fun jsBitnetGemvTq2_0(mod: JsAny, activationPtr: Int, activationScale: Float, weightPtr: Int, inputDim: Int, outputDim: Int, outPtr: Int): Unit =
    js("mod._skainet_bitnet_gemv_tq2_0(activationPtr, 0, activationScale, weightPtr, 0, inputDim, outputDim, outPtr, 0)")

private fun jsCrossOriginIsolated(): Boolean = js("typeof crossOriginIsolated !== 'undefined' && crossOriginIsolated === true")

private fun jsHardwareConcurrency(): Int = js(
    """
    (function() {
      if (typeof navigator !== 'undefined' && typeof navigator.hardwareConcurrency === 'number') return navigator.hardwareConcurrency;
      if (typeof process !== 'undefined' && process.versions != null && process.versions.node != null) {
        try { return require('os').cpus().length; } catch (e) { return 0; }
      }
      return 0;
    })()
    """,
)
